package net.ccbluex.liquidbounce.injection.mixins.minecraft.render.entity;

import net.ccbluex.liquidbounce.features.module.modules.render.ModuleChams;
import net.minecraft.client.renderer.entity.EntityRenderDispatcher;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(EntityRenderDispatcher.class)
public abstract class MixinEntityRenderDispatcher {

    /**
     * Scopes the chams entity context to a single entity, so it cannot leak into entities or
     * block entities submitted after a chams target.
     */
    @Inject(method = "submit", at = {@At("HEAD"), @At("RETURN")})
    private void clearChamsEntityContext(CallbackInfo ci) {
        ModuleChams.INSTANCE.clearEntityContext();
    }

}
