        ⠗⠑⠞⠥⠗⠝ ⠊⠋ (⠎⠏⠕⠞ == ⠝⠥⠇⠇ && ⠗⠕⠞⠁⠞⠊⠕⠝⠎.⠁⠊⠍⠞⠓⠗⠕⠥⠛⠓⠺⠁⠇⠇⠎) {
