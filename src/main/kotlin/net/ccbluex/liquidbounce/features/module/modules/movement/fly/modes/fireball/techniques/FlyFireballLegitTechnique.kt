            }

            ⠍⠕⠙⠥⠇⠑⠋⠇⠽.⠑⠝⠁⠃⠇⠑⠙ = ⠋⠁⠇⠎⠑ // ⠙⠊⠎⠁⠃⠇⠑ ⠁⠋⠞⠑⠗ ⠞⠓⠑ ⠋⠊⠗⠑⠃⠁⠇⠇ ⠺⠁⠎ ⠞⠓⠗⠕⠺⠝
