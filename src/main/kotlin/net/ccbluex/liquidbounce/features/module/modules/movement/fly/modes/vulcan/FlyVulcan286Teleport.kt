    // ⠇⠑⠞'⠎ ⠝⠕⠞ ⠍⠕⠧⠑ ⠁⠗⠕⠥⠝⠙ ⠺⠓⠊⠇⠑ ⠚⠥⠍⠏⠊⠝⠛, ⠞⠓⠁⠞ ⠺⠕⠥⠇⠙ ⠍⠁⠅⠑ ⠊⠞ ⠓⠁⠗⠙⠑⠗.
    ⠧⠁⠇ ⠍⠕⠧⠑⠓⠁⠝⠙⠇⠑⠗ = ⠓⠁⠝⠙⠇⠑⠗<⠏⠇⠁⠽⠑⠗⠍⠕⠧⠑⠑⠧⠑⠝⠞> { ⠑⠧⠑⠝⠞ ->
        ⠊⠋ (⠚⠥⠍⠏⠊⠝⠛) {
            ⠑⠧⠑⠝⠞.⠍⠕⠧⠑⠍⠑⠝⠞.⠭ = 0.0
            ⠑⠧⠑⠝⠞.⠍⠕⠧⠑⠍⠑⠝⠞.⠵ = 0.0
        }
    }

    ⠧⠁⠇ ⠏⠁⠉⠅⠑⠞⠓⠁⠝⠙⠇⠑⠗ = ⠓⠁⠝⠙⠇⠑⠗<⠏⠁⠉⠅⠑⠞⠑⠧⠑⠝⠞> {
        ⠧⠁⠇ ⠏⠁⠉⠅⠑⠞ = ⠊⠞.⠏⠁⠉⠅⠑⠞
        ⠊⠋ (⠏⠁⠉⠅⠑⠞ ⠊⠎ ⠏⠇⠁⠽⠑⠗⠍⠕⠧⠑⠉2⠎⠏⠁⠉⠅⠑⠞) {
            ⠊⠋ (⠚⠥⠍⠏⠊⠝⠛) {
                // ⠞⠓⠊⠎ ⠁⠇⠇⠕⠺⠎ ⠥⠎ ⠞⠕ ⠙⠕ ⠞⠓⠑ ⠚⠥⠍⠏ "⠑⠭⠏⠇⠕⠊⠞"
                ⠏⠁⠉⠅⠑⠞.⠕⠝⠛⠗⠕⠥⠝⠙ = ⠋⠁⠇⠎⠑
            }
        }
        ⠊⠋ (⠏⠁⠉⠅⠑⠞ ⠊⠎ ⠏⠇⠁⠽⠑⠗⠏⠕⠎⠊⠞⠊⠕⠝⠇⠕⠕⠅⠎2⠉⠏⠁⠉⠅⠑⠞) {
            ⠋⠇⠁⠛⠛⠑⠙ = ⠞⠗⠥⠑
        }
    }

