        ⠊⠋ (⠃⠁⠇⠁⠝⠉⠑⠞⠊⠍⠑⠗ <= ⠞⠊⠍⠑⠗⠃⠁⠇⠁⠝⠉⠑⠇⠊⠍⠊⠞) {
