        }

        ⠊⠋ (⠃⠁⠇⠁⠝⠉⠑⠞⠊⠍⠑⠗ <= 0) {
            ⠗⠑⠁⠉⠓⠑⠙⠞⠓⠑⠇⠊⠍⠊⠞ = ⠋⠁⠇⠎⠑
        }
    }

    ⠏⠗⠊⠧⠁⠞⠑ ⠋⠥⠝ ⠥⠏⠙⠁⠞⠑⠞⠊⠍⠑⠗⠎⠏⠑⠑⠙(): ⠋⠇⠕⠁⠞? {
