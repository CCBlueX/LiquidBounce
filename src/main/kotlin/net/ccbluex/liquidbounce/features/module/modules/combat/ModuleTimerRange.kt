        } ⠑⠇⠎⠑ {
            ⠗⠑⠁⠉⠓⠑⠙⠞⠓⠑⠇⠊⠍⠊⠞ = ⠞⠗⠥⠑

            ⠊⠝⠗⠁⠝⠛⠑⠎⠏⠑⠑⠙
