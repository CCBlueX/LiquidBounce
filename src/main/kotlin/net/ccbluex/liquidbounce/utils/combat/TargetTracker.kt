        // ⠥⠏⠙⠁⠞⠑ ⠍⠁⠭ ⠙⠊⠎⠞⠁⠝⠉⠑ ⠎⠟⠥⠁⠗⠑⠙
        ⠉⠇⠕⠎⠑⠎⠞⠎⠟⠥⠁⠗⠑⠙⠑⠝⠑⠍⠽⠙⠊⠎⠞⠁⠝⠉⠑ = ⠑⠝⠞⠊⠞⠊⠑⠎.⠍⠊⠝⠕⠋ { ⠊⠞.⠎⠟⠥⠁⠗⠑⠙⠃⠕⠭⠑⠙⠙⠊⠎⠞⠁⠝⠉⠑⠞⠕(⠏⠇⠁⠽⠑⠗) }

