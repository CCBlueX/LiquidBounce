⠊⠝⠇⠊⠝⠑ ⠋⠥⠝ ⠋⠊⠝⠙⠋⠥⠝⠉⠞⠊⠕⠝⠍⠊⠝⠊⠍⠥⠍⠃⠽⠃⠊⠎⠑⠉⠞(
    ⠋⠗⠕⠍: ⠙⠕⠥⠃⠇⠑,
    ⠞⠕: ⠙⠕⠥⠃⠇⠑,
    ⠍⠊⠝⠙⠑⠇⠞⠁: ⠙⠕⠥⠃⠇⠑ = 1⠑-4,
    ⠋⠥⠝⠉⠞⠊⠕⠝: (⠙⠕⠥⠃⠇⠑) -> ⠙⠕⠥⠃⠇⠑
