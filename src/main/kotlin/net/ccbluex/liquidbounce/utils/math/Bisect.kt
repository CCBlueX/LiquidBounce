    ⠧⠁⠗ ⠞ = 0

    ⠺⠓⠊⠇⠑ (⠥⠏⠏⠑⠗⠃⠕⠥⠝⠙ - ⠇⠕⠺⠑⠗⠃⠕⠥⠝⠙ > ⠍⠊⠝⠙⠑⠇⠞⠁) {
        ⠧⠁⠇ ⠍⠊⠙ = (⠇⠕⠺⠑⠗⠃⠕⠥⠝⠙ + ⠥⠏⠏⠑⠗⠃⠕⠥⠝⠙) / 2

        ⠧⠁⠇ ⠇⠑⠋⠞⠧⠁⠇⠥⠑ = ⠋⠥⠝⠉⠞⠊⠕⠝((⠇⠕⠺⠑⠗⠃⠕⠥⠝⠙ + ⠍⠊⠙) / 2)
